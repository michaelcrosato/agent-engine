import { z } from 'zod';
import type { ContentKind } from '../../engine/content/defineContentKind.ts';
import type { ComponentType } from '../../engine/core/defineComponent.ts';
import type { Engine } from '../../engine/core/Engine.ts';
import { schemaTable } from './schemaTable.ts';

type Files = Map<string, string>;

const json = (v: unknown) => `${JSON.stringify(v, null, 2)}\n`;

function toSchema(s: z.ZodType): Record<string, unknown> {
  const js = z.toJSONSchema(s, { io: 'input', unrepresentable: 'any' }) as Record<string, unknown>;
  delete js.$schema;
  const props = js.properties as Record<string, unknown> | undefined;
  if (props) props.$schema = { type: 'string', description: 'Editor schema hint (ignored by the engine)' };
  return js;
}

function kindSchema(kind: ContentKind, components: readonly ComponentType[]): Record<string, unknown> {
  const js = toSchema(kind.schema);
  if (kind.name === 'prefab') {
    const props = js.properties as Record<string, Record<string, unknown>>;
    props.components = {
      type: 'object',
      description: 'Component name → fields',
      additionalProperties: false,
      properties: Object.fromEntries(
        components.map((c) => [c.name, { $ref: `components.schema.json#/$defs/${c.name}` }]),
      ),
    };
  }
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    title: `${kind.name} (data/${kind.folder})`,
    description: kind.doc,
    ...js,
  };
}

/**
 * Everything derived from the schemas: JSON Schemas for editors (schemas/*.json + VS Code
 * mapping) and reference docs for components and content kinds. `npm run check` keeps them fresh.
 */
export function generateSchemas(engines: readonly Engine[]): Files {
  const files: Files = new Map();
  const comps = new Map<string, ComponentType>();
  const kinds = new Map<string, ContentKind>();
  for (const e of engines) {
    for (const c of e.componentTypes()) comps.set(c.name, c);
    for (const k of e.content.kindList()) kinds.set(k.name, k);
  }
  const compList = [...comps.values()].sort((a, b) => a.name.localeCompare(b.name));
  files.set(
    'schemas/components.schema.json',
    json({
      $schema: 'https://json-schema.org/draft/2020-12/schema',
      title: 'Components',
      $defs: Object.fromEntries(compList.map((c) => [c.name, { description: c.doc, ...toSchema(c.schema) }])),
    }),
  );
  const fileMatch: { fileMatch: string[]; url: string }[] = [];
  for (const k of [...kinds.values()].sort((a, b) => a.name.localeCompare(b.name))) {
    files.set(`schemas/${k.name}.schema.json`, json(kindSchema(k, compList)));
    fileMatch.push({ fileMatch: [`**/data/${k.folder}/**/*.json`], url: `./schemas/${k.name}.schema.json` });
  }
  files.set('.vscode/settings.json', json({ 'json.schemas': fileMatch }));
  const compDoc = [
    '# Components (generated)',
    '',
    'Generated from the component schemas by `npm run check`. Do not edit.',
    '',
  ];
  for (const c of compList)
    compDoc.push(
      `## ${c.name}`,
      '',
      c.doc,
      '',
      '```',
      ...schemaTable(c.schema).map((l) => l.trimStart()),
      '```',
      '',
    );
  files.set('docs/reference/components.md', compDoc.join('\n'));
  const kindDoc = [
    '# Content kinds (generated)',
    '',
    'Data file schemas, generated by `npm run check`. Do not edit.',
    '',
  ];
  for (const k of kinds.values()) {
    kindDoc.push(
      `## ${k.name} — data/${k.folder}/<id>.json`,
      '',
      k.doc,
      '',
      '```',
      ...schemaTable(k.schema).map((l) => l.trimStart()),
      '```',
      '',
    );
  }
  files.set('docs/reference/content-kinds.md', kindDoc.join('\n'));
  return files;
}
